// SourceTreeHash matches the released length-framed source hash, including its
// historic final hash-of-digest step. No Unicode normalization is performed.
func SourceTreeHash(root string) (string, error) {
	var paths []string
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("linked canonical source")
		}
		if !d.IsDir() {
			ext := strings.ToLower(filepath.Ext(path))
			if ext == ".yaml" || ext == ".yml" || ext == ".md" {
				paths = append(paths, path)
			}
		}
		return nil
	})
	if err != nil {
		return "", err
	}
	sort.Slice(paths, func(i, j int) bool { return filepath.ToSlash(paths[i]) < filepath.ToSlash(paths[j]) })
	h := sha256.New()
	h.Write([]byte("opensocrates-content-tree-v1\x00"))
	var length [8]byte
	for _, p := range paths {
		rel, _ := filepath.Rel(root, p)
		name := []byte(filepath.ToSlash(rel))
		var data []byte
		if strings.ToLower(filepath.Ext(p)) == ".md" {
			b, e := os.ReadFile(p)
			if e != nil {
				return "", e
			}
			data = []byte(markdown(string(b)))
		} else {
			v, e := ReadObject(p)
			if e != nil {
				return "", e
			}
			data, e = Canonical(v)
			if e != nil {
				return "", e
			}
		}
		binary.BigEndian.PutUint64(length[:], uint64(len(name)))
		h.Write(length[:])
		h.Write(name)
		binary.BigEndian.PutUint64(length[:], uint64(len(data)))
		h.Write(length[:])
		h.Write(data)
	}
	return digest(h.Sum(nil)), nil
}

var semanticFields = []string{"content_revision", "method_ids", "methods", "locale_messages", "prompt_fragments", "policy_versions"}

func SemanticHash(bundle map[string]any) (string, error) {
	projection := map[string]any{}
	for _, key := range semanticFields {
		v, ok := bundle[key]
		if !ok {
			return "", fmt.Errorf("missing semantic field %s", key)
		}
		projection[key] = v
	}
	b, e := Canonical(projection)
	if e != nil {
		return "", e
	}
	return digest(append([]byte("opensocrates-runtime-semantics-v1\x00"), b...)), nil
}
func orderedKeys(v map[string]any) []any {
	keys := make([]string, 0, len(v))
	for k := range v {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	result := make([]any, 0, len(v))
	for _, k := range keys {
		result = append(result, k)
	}
	return result
}
func unique(values []any) []any {
	r := []any{}
	seen := map[string]bool{}
	for _, v := range values {
		s := str(v)
		if !seen[s] {
			seen[s] = true
			r = append(r, v)
		}
	}
	return r
}
func flatten(v map[string]any, prefix string, out map[string]any) error {
	for k, x := range v {
		key := k
		if prefix != "" {
			key = prefix + "." + k
		}
		if child := obj(x); child != nil {
			if err := flatten(child, key, out); err != nil {
				return err
			}
		} else if _, ok := x.(string); ok {
			out[key] = x
		} else {
			return fmt.Errorf("locale message %s must be string", key)
		}
	}
	return nil
}

// GenerateContent parses canonical authoring sources, derives both projections,
// response policy, source identity and semantic identity, then embeds the exact
// generated bytes. It never reads compiled output to perform compilation.
func GenerateContent(root, productVersion string) error {
	base := filepath.Join(root, "content")
	catalog, err := ReadObject(filepath.Join(base, "catalog.yaml"))
	if err != nil {
		return err
	}
	teachers, err := ReadObject(filepath.Join(base, "teacher-questions.yaml"))
	if err != nil {
		return err
	}
	if err = validateReleasedLocaleSources(root, catalog, teachers); err != nil {
		return err
	}
	revision := catalog["content_revision"]
	if jsonToken(revision) != "4" || jsonToken(teachers["content_revision"]) != "4" {
		return fmt.Errorf("v1.6.0 requires released content revision 4")
	}
	ids := []any{}
	for _, f := range arr(catalog["families"]) {
		ids = append(ids, arr(obj(f)["method_ids"])...)
	}
	if len(ids) != 48 || len(unique(ids)) != 48 {
		return fmt.Errorf("expected 48 unique frozen methods")
	}
	methods := []any{}
	entries := []any{}
	injectable := []any{}
	for _, rawID := range ids {
		id := str(rawID)
		if id == "" || strings.ContainsAny(id, "/\\.") {
			return fmt.Errorf("unsafe method id")
		}
		dir := filepath.Join(base, "methods", id)
		authored, e := ReadObject(filepath.Join(dir, "method.yaml"))
		if e != nil {
			return e
		}
		if str(authored["id"]) != id || jsonToken(authored["content_revision"]) != jsonToken(revision) {
			return fmt.Errorf("method identity mismatch %s", id)
		}
		if e = validateSourceSchema(root, "method-authoring.schema.json", authored); e != nil {
			return fmt.Errorf("method %s: %w", id, e)
		}
		routing := clone(obj(authored["routing"]))
		positive := obj(routing["positive_features"])
		negative := clone(obj(routing["negative_features"]))
		contra := append([]any{}, arr(routing["contraindications"])...)
		procedure := map[string]any{}
		complement := map[string]any{}
		var englishCases []any
		for _, locale := range releasedLocales {
			p, e := os.ReadFile(filepath.Join(dir, "procedure."+locale+".md"))
			if e != nil {
				return e
			}
			text := markdown(string(p))
			if e = validateProcedureLocale(text, locale); e != nil {
				return fmt.Errorf("%s.%s: %w", id, locale, e)
			}
			questions := arr(obj(obj(teachers["methods"])[id])[locale])
			if len(questions) != 3 {
				return fmt.Errorf("teacher questions %s.%s", id, locale)
			}
			bullets := []string{}
			for _, q := range questions {
				question := str(q)
				if !strings.HasSuffix(question, "?") || len([]rune(question)) < 20 || len([]rune(question)) > 220 || strings.ContainsAny(question, "\n\x00") {
					return fmt.Errorf("invalid teacher question")
				}
				bullets = append(bullets, "- "+question)
			}
			theory := markdown("## Teacher questions\n\n" + strings.Join(bullets, "\n") + "\n\n" + text)
			procedure[locale] = theory
			position := strings.Index(text, "## Complement handoff\n")
			if position < 0 {
				return fmt.Errorf("missing complement handoff")
			}
			complement[locale] = markdown(text[position+len("## Complement handoff\n"):])
			cases, e := ReadObject(filepath.Join(dir, "cases."+locale+".yaml"))
			if e != nil {
				return e
			}
			if e = validateCases(id, cases); e != nil {
				return e
			}
			if locale == "en" {
				englishCases = arr(cases["cases"])
			}
			examples := []any{}
			for _, raw := range arr(cases["cases"]) {
				c := obj(raw)
				example := clone(c)
				example["schema"] = schema("template-example")
				example["case_id"] = c["id"]
				delete(example, "id")
				example["template_prompt"] = c["prompt"]
				delete(example, "prompt")
				examples = append(examples, example)
			}
			injectable = append(injectable, map[string]any{"schema": schema("injectable-reasoning-content"), "method_id": id, "content_revision": revision, "locale": locale, "display_name": obj(authored["display_name"])[locale], "theory": theory, "template_examples": examples})
		}
		confused := []any{}
		related := append([]any{}, arr(obj(authored["complements"])["preferred"])...)
		for _, raw := range englishCases {
			c := obj(raw)
			if c["kind"] == "negative" {
				confused = append(confused, arr(c["decisive_features"])...)
				if c["expected_route"] != nil && c["expected_route"] != id {
					related = append(related, c["expected_route"])
				}
			}
		}
		// Python preserves authoring map insertion order for feature projections.
		positiveOrder, e := sourceFieldKeys(filepath.Join(dir, "method.yaml"), "positive_features")
		if e != nil {
			return e
		}
		negativeOrder, e := sourceFieldKeys(filepath.Join(dir, "method.yaml"), "negative_features")
		if e != nil {
			return e
		}
		_ = positive
		entries = append(entries, map[string]any{"schema": schema("selection-catalog-entry"), "method_id": id, "family": authored["family"], "content_revision": revision, "display_name": authored["display_name"], "core_purpose": authored["plain_action"], "suitable_features": positiveOrder, "unsuitable_features": unique(append(negativeOrder, contra...)), "commonly_confused_features": unique(confused), "related_method_ids": unique(related), "injectable_content_locator": fmt.Sprintf("injectable-content/%s/%s", jsonToken(revision), id)})
		negative["mechanical"] = 3
		routing["negative_features"] = negative
		routing["contraindications"] = append(contra, "mechanical")
		method := map[string]any{"schema": schema("compiled-method"), "id": id, "family": authored["family"], "content_revision": revision, "display_name": authored["display_name"], "plain_action": authored["plain_action"], "participation": authored["participation"], "routing": routing, "output_contract": authored["output_contract"], "complements": authored["complements"], "procedure": procedure, "complement_fragment": complement}
		methods = append(methods, method)
	}
	sort.Slice(methods, func(i, j int) bool { return str(obj(methods[i])["id"]) < str(obj(methods[j])["id"]) })
	sortedIDs := []any{}
	for _, m := range methods {
		sortedIDs = append(sortedIDs, obj(m)["id"])
	}
	messages := map[string]any{}
	fragments := map[string]any{}
	for _, locale := range releasedLocales {
		v, e := ReadObject(filepath.Join(base, "locales", locale+".yaml"))
		if e != nil {
			return e
		}
		flat := map[string]any{}
		if e = flatten(obj(v["messages"]), "", flat); e != nil {
			return e
		}
		messages[locale] = flat
	}
	for _, locale := range releasedLocales {
		if jsonToken(orderedKeys(obj(messages["en"]))) != jsonToken(orderedKeys(obj(messages[locale]))) {
			return fmt.Errorf("locale keys differ: %s", locale)
		}
	}
	for _, key := range []string{"controller", "participation_rigor", "routing_classifier", "framing", "evidence_card_completion", "cross_exam", "strict_second_pass", "capability_notice"} {
		pair := map[string]any{}
		for _, locale := range releasedLocales {
			v := obj(messages[locale])["prompt."+key]
			if str(v) == "" {
				return fmt.Errorf("missing prompt fragment %s", key)
			}
			pair[locale] = v
		}
		fragments[key] = pair
	}
	policies := map[string]any{}
	for _, key := range []string{"participation", "risk", "routing", "card"} {
		p, e := ReadObject(filepath.Join(base, key+"-policy.yaml"))
		if e != nil {
			return e
		}
		b, e := Canonical(p)
		if e != nil {
			return e
		}
		policies[key] = map[string]any{"version": p["version"], "sha256": digest(b)}
	}
	tree, e := SourceTreeHash(base)
	if e != nil {
		return e
	}
	if tree != "sha256:993c30191b0d2b67af88a25c2631d9e8fddeeaf9dadfd0ff4fb07dd62539dcab" {
		return fmt.Errorf("revision 4 source differs from released v1.5.1 baseline; a separate content revision is required")
	}
	bundle := map[string]any{"schema": schema("compiled-content-bundle"), "product_version": productVersion, "content_revision": revision, "method_ids": sortedIDs, "methods": methods, "locale_messages": messages, "prompt_fragments": fragments, "policy_versions": policies, "source_tree_hash": tree}
	semantic, e := SemanticHash(bundle)
	if e != nil {
		return e
	}
	if semantic != "sha256:835a1e32695e863b3696c3bf5dcf1acb7faa580d889129e617524fbc0d9908e6" {
		return fmt.Errorf("released v1.5.1 semantic identity changed")
	}
	bundle["normalized_semantic_hash"] = semantic
	projections := map[string]any{"schema": schema("reasoning-content-projections"), "content_revision": revision, "selection_catalog": map[string]any{"schema": schema("selection-catalog"), "content_revision": revision, "entries": entries}, "injectable_content": injectable}
	policy, e := ReadObject(filepath.Join(base, "response-policy.yaml"))
	if e != nil {
		return e
	}
	locales := map[string]any{}
	for _, locale := range releasedLocales {
		v, e := ReadObject(filepath.Join(base, "response-policy", locale+".yaml"))
		if e != nil {
			return e
		}
		locales[locale] = v
	}
	policy["locales"] = locales
	for name, value := range map[string]any{"compiled-content.bundle.json": bundle, "compiled-reasoning-content.bundle.json": projections, "compiled-response-policy.json": policy} {
		data, e := Canonical(value)
		if e != nil {
			return e
		}
		if e = writeData(filepath.Join(base, name), data, 0644); e != nil {
			return e
		}
		if e = writeData(filepath.Join(root, "src/opensocrates/internal/content/assets", name), data, 0644); e != nil {
			return e
		}
	}
	return nil
}

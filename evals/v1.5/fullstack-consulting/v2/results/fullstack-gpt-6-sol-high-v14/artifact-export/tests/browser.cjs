const {chromium} = require('playwright');
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.connect(process.env.EVAL_BROWSER_WS);
  const context = await browser.newContext({viewport: {width: 1365, height: 900}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(process.env.BASE_URL || 'http://127.0.0.1:8765/');
    await page.getByTestId('login-email').fill('operator@north.example');
    await page.getByTestId('login-password').fill('DepotDemo!2026');
    await page.getByTestId('login-submit').click();
    await page.getByTestId('inventory-table').waitFor();
    await page.getByTestId('nav-orders').click();
    await page.getByTestId('new-order').click();
    const reference = 'browser-' + Date.now();
    await page.getByTestId('order-client-ref').fill(reference);
    await page.getByTestId('line-sku').first().selectOption('BOLT');
    await page.getByTestId('line-quantity').first().fill('2');
    await page.getByTestId('add-line').click();
    await page.getByTestId('line-sku').nth(1).selectOption('CABLE');
    await page.getByTestId('line-quantity').nth(1).fill('1');
    await page.getByTestId('submit-order').click();
    await page.getByTestId('order-detail').getByText(reference).waitFor();
    assert.match(await page.getByTestId('order-detail').innerText(), /draft/i);
    await page.getByTestId('reserve-order').click();
    await page.getByTestId('ship-order').waitFor();
    await page.getByTestId('ship-order').click();
    await page.getByTestId('submit-return').waitFor();
    await page.getByTestId('return-quantity').first().fill('1');
    await page.getByTestId('submit-return').click();
    await page.waitForFunction(() => document.querySelector('#detail-version')?.textContent === '4');
    assert.match(await page.getByTestId('order-detail').innerText(), /shipped/i);
    await page.getByTestId('return-quantity').first().fill('1');
    await page.getByTestId('return-quantity').nth(1).fill('1');
    await page.getByTestId('submit-return').click();
    await page.waitForFunction(() => document.querySelector('#detail-status')?.textContent === 'returned');
    await page.getByTestId('nav-audit').click();
    await page.getByTestId('audit-table').waitFor();
    assert.match(await page.getByTestId('audit-table').innerText(), /order returned/);
    await page.screenshot({path: 'browser-workflow.png', fullPage: true});
    await page.getByTestId('nav-orders').click();
    await page.locator('#search-orders').fill(reference);
    await page.getByRole('button', {name: 'Apply filters'}).click();
    assert.equal(await page.locator('#orders-body tr').count(), 1);
    await page.getByTestId('logout').click();
    await page.getByTestId('login-email').fill('admin@north.example');
    await page.getByTestId('login-password').fill('DepotDemo!2026');
    await page.getByTestId('login-submit').click();
    await page.getByTestId('inventory-table').waitFor();
    const before = Number(await page.getByTestId('inventory-table').locator('tbody tr').first().locator('td').nth(2).innerText());
    const adjust = page.locator('form.adjust-form').first();
    await adjust.locator('input').first().fill('2');
    await adjust.locator('input').nth(1).fill('browser count');
    await adjust.getByRole('button', {name: 'Save adjustment'}).click();
    await page.waitForFunction(value => Number(document.querySelector('[data-testid="inventory-table"] tbody tr td:nth-child(3)')?.textContent) === value, before + 2);
    await page.getByTestId('logout').click();
    await page.getByTestId('login-email').fill('viewer@south.example');
    await page.getByTestId('login-password').fill('DepotDemo!2026');
    await page.getByTestId('login-submit').click();
    await page.getByTestId('inventory-table').waitFor();
    await page.getByTestId('nav-orders').click();
    await page.getByText('No orders match these filters.').waitFor();
    assert.equal(await page.getByTestId('new-order').count(), 0);
    await page.setViewportSize({width: 390, height: 844});
    await page.getByTestId('nav-inventory').click();
    await page.getByTestId('inventory-table').waitFor();
    await page.screenshot({path: 'browser-mobile.png', fullPage: true});
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log(JSON.stringify({status: 'passed', desktopWorkflow: 'create/reserve/ship/partial return/full return/audit/search/admin adjustment', viewerIsolation: true, mobileViewport: '390x844', pageErrors: errors.length}));
  } finally {
    await context.close();
    await browser.close();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });

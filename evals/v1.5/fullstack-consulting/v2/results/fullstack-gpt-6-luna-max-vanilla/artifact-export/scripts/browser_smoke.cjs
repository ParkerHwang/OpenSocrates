const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
  const origin = process.env.DEPOTFLOW_URL || 'http://127.0.0.1:8000';
  const evidence = path.resolve(__dirname, '..', 'evidence');
  fs.mkdirSync(evidence, { recursive: true });
  const browser = await chromium.connect(process.env.EVAL_BROWSER_WS);
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  page.on('console', message => { if (message.type() === 'error') failures.push(message.text()); });
  async function submitAndWait(control, pathSuffix) {
    const responsePromise = page.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname.endsWith(pathSuffix));
    await control.click();
    const response = await responsePromise;
    assert.equal(response.status(), 200, `${pathSuffix} failed with ${response.status()}`);
    return response.json();
  }

  await page.goto(origin);
  await page.getByTestId('login-email').fill('operator@north.example');
  await page.getByTestId('login-password').fill('DepotDemo!2026');
  await page.getByTestId('login-submit').click();
  await page.getByRole('heading', { name: 'Inventory', exact: true }).waitFor();
  await page.getByTestId('inventory-table').waitFor();
  assert.equal(await page.getByTestId('inventory-table').locator('tbody tr').count(), 3);
  await page.screenshot({ path: path.join(evidence, 'browser-inventory.png'), fullPage: true });

  await page.getByTestId('nav-orders').click();
  await page.getByTestId('new-order').click();
  const clientRef = `browser-flow-${Date.now()}`;
  await page.getByTestId('order-client-ref').fill(clientRef);
  await page.getByTestId('line-sku').nth(0).selectOption('BOLT');
  await page.getByTestId('line-quantity').nth(0).fill('2');
  await page.getByTestId('add-line').click();
  await page.getByTestId('line-sku').nth(1).selectOption('CABLE');
  await page.getByTestId('line-quantity').nth(1).fill('1');
  await page.getByTestId('submit-order').click();
  const detail = page.getByTestId('order-detail');
  await detail.getByText(clientRef, { exact: true }).waitFor();
  await detail.getByText('draft', { exact: true }).waitFor();
  await submitAndWait(page.getByTestId('reserve-order'), '/reserve');
  await detail.getByText('reserved', { exact: true }).waitFor();
  await submitAndWait(page.getByTestId('ship-order'), '/ship');
  await detail.getByText('shipped', { exact: true }).waitFor();
  const returnInputs = page.getByTestId('return-quantity');
  await returnInputs.nth(0).fill('1');
  await returnInputs.nth(1).fill('0');
  const partial = await submitAndWait(page.getByTestId('submit-return'), '/returns');
  assert.equal(partial.status, 'shipped');
  await detail.getByText(new RegExp(`Version ${partial.version}`)).waitFor();
  await page.getByTestId('return-quantity').nth(0).fill('1');
  await page.getByTestId('return-quantity').nth(1).fill('1');
  const complete = await submitAndWait(page.getByTestId('submit-return'), '/returns');
  assert.equal(complete.status, 'returned');
  await detail.getByText('returned', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(evidence, 'browser-order-workflow.png'), fullPage: true });
  await page.getByRole('searchbox', { name: 'Search orders' }).fill(clientRef);
  await page.getByText(clientRef, { exact: true }).first().waitFor();
  await page.getByTestId('nav-audit').click();
  await page.getByTestId('audit-table').waitFor();
  assert.ok(await page.getByTestId('audit-table').innerText().then(text => text.includes('order.returns')));
  await page.getByTestId('logout').click();

  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByTestId('login-email').fill('viewer@north.example');
  await page.getByTestId('login-password').fill('DepotDemo!2026');
  await page.getByTestId('login-submit').click();
  await page.getByRole('heading', { name: 'Inventory', exact: true }).waitFor();
  await page.getByTestId('inventory-table').waitFor();
  const inventoryMobile = await page.evaluate(() => ({ viewport: document.documentElement.clientWidth, page: document.documentElement.scrollWidth }));
  assert.ok(inventoryMobile.page <= inventoryMobile.viewport, `mobile inventory overflow: ${JSON.stringify(inventoryMobile)}`);
  await page.getByTestId('nav-orders').click();
  await page.getByRole('heading', { name: 'Orders', exact: true }).waitFor();
  await page.getByTestId('orders-table').waitFor();
  assert.equal(await page.getByTestId('new-order').count(), 0);
  assert.equal(await page.getByTestId('reserve-order').count(), 0);
  const widths = await page.evaluate(() => ({ viewport: document.documentElement.clientWidth, page: document.documentElement.scrollWidth }));
  assert.ok(widths.page <= widths.viewport, `mobile horizontal overflow: ${JSON.stringify(widths)}`);
  await page.screenshot({ path: path.join(evidence, 'browser-mobile-viewer.png'), fullPage: true });
  assert.deepEqual(failures, []);
  console.log(JSON.stringify({ result: 'PASS', workflow: ['operator login', 'inventory inspect', 'two-line order', 'reserve', 'ship', 'partial return', 'full return', 'search', 'audit', 'logout', 'viewer read-only at 390px'], mobile_inventory: inventoryMobile, mobile_orders: widths, browser_errors: failures, screenshots: ['evidence/browser-inventory.png', 'evidence/browser-order-workflow.png', 'evidence/browser-mobile-viewer.png'] }, null, 2));
  await context.close();
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });

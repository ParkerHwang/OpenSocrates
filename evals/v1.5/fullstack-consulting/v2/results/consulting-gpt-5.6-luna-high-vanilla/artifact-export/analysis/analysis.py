def style_sheet(ws, freeze="A2", widths=None):
    ws.freeze_panes = freeze
    ws.auto_filter.ref = ws.dimensions
    header_fill = PatternFill("solid", fgColor="16324F")
    for cell in ws[1]:
        cell.font = Font(color="FFFFFF", bold=True)
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(vertical="top")
    if widths:
        for col, width in widths.items():
            ws.column_dimensions[col].width = width


def write_df(ws, df, number_formats=None):
    for row in [list(df.columns)] + df.where(pd.notna(df), None).values.tolist():
        ws.append(row)
    style_sheet(ws)
    if number_formats:
        for col, fmt in number_formats.items():
            if col in df.columns:
                idx = list(df.columns).index(col) + 1
                for cell in ws.iter_cols(min_col=idx, max_col=idx, min_row=2):
                    for c in cell: c.number_format = fmt


